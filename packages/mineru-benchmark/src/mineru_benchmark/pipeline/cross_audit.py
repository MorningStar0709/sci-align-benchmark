"""Cross-model adversarial audit for benchmark verification.

Two-stage quality control (audit stage):
  DS + MM independently audit all questions (paper-anchored fact checking)

The arbitration stage (Qwen resolves disagreements) is in cross_arbitrate.py.

Usage:
    # Audit: DS audits all questions
    .venv/bin/python -m mineru_benchmark.pipeline.cross_audit audit \\
        --questions benchmark/dataset/core_v3.json \\
        --auditor deepseek --output benchmark/dataset/audit_by_ds.json

    # Audit: MM audits all questions
    .venv/bin/python -m mineru_benchmark.pipeline.cross_audit audit \\
        --questions benchmark/dataset/core_v3.json \\
        --auditor mimo --output benchmark/dataset/audit_by_mimo.json
"""
