AUDIT_SYSTEM_PROMPT = """You are a control science expert auditor. Your task is to verify the factual correctness of a Q&A pair generated by another AI model, based on the provided paper excerpt.

## Audit Instructions
1. Does the answer contradict the source paper? (major red flag)
2. Is the answer generally consistent with the paper's domain and concepts?
3. Are there any obvious formula errors or factual mistakes?
4. **Important**: The answer may legitimately draw on domain knowledge beyond the paper excerpt — this is ACCEPTABLE as long as it doesn't contradict the paper.
5. For design questions (Dimension D): creative synthesis and engineering reasoning are expected. Do NOT reject just because specific details aren't in the paper.
6. If the answer is largely correct but missing minor details, flag it as partial (pass=true with issues).

## Judgment Criteria
- **pass=true**: Answer is consistent with the paper, may include additional domain knowledge that is reasonable
- **pass=false**: Answer directly contradicts the paper, contains obvious factual errors, or is completely off-topic

Output strict JSON (no other text):
{
  "pass": true,
  "confidence": 0.85,
  "evidence": "Section 3.2 states: '...' The answer correctly reflects this.",
  "issues": ["Minor: answer omits the initial condition x(0)=0"]
}

pass: true if answer is generally consistent with the paper, false only if it contradicts or is off-topic.
confidence: 0.0-1.0, how confident you are in your judgment.
evidence: quote the specific paper passages that support/contradict.
issues: list of specific problems, empty if none."""


def build_audit_user_prompt(question: str, answer: str, paper_text: str) -> str:
    return f"""## Source Paper
{paper_text}

## Question (generated by another model)
{question}

## Answer (generated by another model)
{answer}

Please audit the answer against the source paper."""


# ---------------------------------------------------------------------------
# Core audit
# ---------------------------------------------------------------------------


def audit_one(
    question: dict,
    paper_text: str,
    auditor_provider: str,
    client,
    model: str,
) -> dict:
    """Audit a single question-answer pair against paper text."""
    user_prompt = build_audit_user_prompt(
        question.get("question", ""),
        question.get("answer", ""),
        paper_text,
    )

    for attempt in range(3):
        try:
            kwargs = {
                "model": model,
                "messages": [
                    {"role": "system", "content": AUDIT_SYSTEM_PROMPT},
                    {"role": "user", "content": user_prompt},
                ],
                "temperature": 0.1,
                "max_tokens": 1024,
                "response_format": {"type": "json_object"},
            }
            resp = client.chat.completions.create(**kwargs)
            content = resp.choices[0].message.content.strip()

            json_match = re.search(r'\{[\s\S]*"pass"[\s\S]*\}', content)
            if json_match:
                try:
                    result = json.loads(_sanitize_json_escapes(json_match.group(0)))
                except json.JSONDecodeError:
                    json_match = re.search(r'\{[^{}]*"pass"[^{}]*\}', content, re.DOTALL)
                    if json_match:
                        result = json.loads(_sanitize_json_escapes(json_match.group(0)))
                    else:
                        raise
            else:
                generic_match = re.search(r'\{[\s\S]+\}', content)
                if generic_match:
                    result = json.loads(_sanitize_json_escapes(generic_match.group(0)))
                else:
                    result = json.loads(_sanitize_json_escapes(content))
            return {
                "id": question.get("id", ""),
                "pass": result.get("pass", False),
                "confidence": float(result.get("confidence", 0.5)),
                "evidence": result.get("evidence", ""),
                "issues": result.get("issues", []),
                "raw_response": content,
            }
        except (json.JSONDecodeError, KeyError) as e:
            if attempt < 2:
                time.sleep(2 ** attempt)
                continue
            return {
                "id": question.get("id", ""),
                "pass": None, "confidence": 0, "evidence": "",
                "issues": [f"Parse error after 3 attempts: {e}"],
                "raw_response": locals().get('content', ''),
            }
        except Exception as e:
            if attempt < 2:
                time.sleep(3 ** attempt)
                continue
            return {
                "id": question.get("id", ""),
                "pass": None, "confidence": 0, "evidence": "",
                "issues": [f"API error: {e}"],
                "raw_response": "",
            }

    return {"id": question.get("id", ""), "pass": None, "confidence": 0, "evidence": "", "issues": ["Unknown error"]}


