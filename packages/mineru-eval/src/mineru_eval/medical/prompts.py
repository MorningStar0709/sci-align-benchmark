def _build_identify_rubric(difficulty: str) -> tuple[str, str]:
    """Build identify-dimension rubric for given difficulty."""
    criteria = {
        "L1": (
            "## 评分标准（L1-基础：显式概念识别）\n"
            "- 1.0 — 完整识别：准确识别医学文本中**显式**提到的控制概念，给出标准定义，并指出文本中的对应描述。\n"
            "- 0.75 — 基本识别：识别显式概念但定义不够精确，或遗漏 1 个次要概念。\n"
            "- 0.5 — 部分识别：识别 1 个显式概念但定义模糊，或医学对应关系有误。\n"
            "- 0.25 — 有限识别：仅提到控制理论术语但无定义或对应关系。\n"
            "- 0.0 — 未识别：未检测到任何控制理论概念，或概念与医学文本无关。"
        ),
        "L2": (
            "## 评分标准（L2-标准：隐含概念识别）\n"
            "- 1.0 — 完整识别：准确识别医学文本中**隐含**的控制概念，建立精确对应关系，并引用文本证据。\n"
            "- 0.75 — 基本识别：识别隐含概念但对应关系不够精确，或证据引用不完整。\n"
            "- 0.5 — 部分识别：识别 1 个隐含概念但医学解释有误，或遗漏多个概念。\n"
            "- 0.25 — 有限识别：仅识别显式概念（未深入到隐含层），或对应关系完全错误。\n"
            "- 0.0 — 未识别：未检测到任何控制理论概念。"
        ),
        "L3": (
            "## 评分标准（L3-进阶：多概念跨分支映射）\n"
            "- 1.0 — 完整识别：识别多个隐含概念，完成跨控制分支映射，并给出完整理论解释。\n"
            "- 0.75 — 基本识别：识别多个概念但跨分支映射有 1 处错误，或理论解释不完整。\n"
            "- 0.5 — 部分识别：识别 2 个概念但仅完成单分支映射，或理论解释有重大缺陷。\n"
            "- 0.25 — 有限识别：仅识别 1 个概念，无跨分支映射。\n"
            "- 0.0 — 未识别：概念识别错误或完全缺失。"
        ),
        "L4": (
            "## 评分标准（L4-高级：深层隐含概念 + 反直觉映射）\n"
            "- 1.0 — 完整识别：识别深层隐含概念，发现反直觉映射关系，并给出完整理论链证明。\n"
            "- 0.75 — 基本识别：识别深层概念但反直觉映射论证有 1 处逻辑跳跃。\n"
            "- 0.5 — 部分识别：识别 1-2 个深层概念但映射关系不够深入，或缺乏理论证明。\n"
            "- 0.25 — 有限识别：仅识别表层概念，未触及深层隐含关系。\n"
            "- 0.0 — 未识别：映射关系完全错误或概念识别缺失。"
        ),
    }
    sys_prompt = (
        "你是一位医学与控制科学跨领域评分专家。你需要评估模型对医学场景中控制理论概念的识别能力。\n\n"
        "## 评分维度：identify（概念识别）\n\n"
        f"{criteria.get(difficulty, criteria['L2'])}\n\n"
        "## 评判原则\n"
        "- 宽松匹配：接受同义表达（如\"闭环调节\"与\"负反馈\"等价）\n"
        "- 关注概念与医学场景的对应关系，而非单纯列举术语\n"
        "- 若模型使用了控制理论框架分析医学问题，即使术语不完全标准也应给分\n\n"
        "请严格按照以下 JSON 格式输出，不要输出任何其他内容：\n"
        '{"score": <分数>, "reason": "<评分理由>", "issues": ["<问题1>", ...]}\n'
        "分数只能是 0.0、0.25、0.5、0.75、1.0 之一。如果没有问题，issues 为空列表 []。"
    )
    usr_template = (
        "## 问题\n{question}\n\n"
        "## 标准答案\n{expected_answer}\n\n"
        "## 模型回答\n{model_answer}\n\n"
        "请根据评分规则对模型回答的概念识别质量进行评分。"
    )
    return sys_prompt, usr_template


def _build_model_rubric(difficulty: str) -> tuple[str, str]:
    """Build model-dimension rubric for given difficulty."""
    criteria = {
        "L1": (
            "## 评分标准（L1-基础：模型名称/类型识别）\n"
            "- 1.0 — 完整建模：给出模型名称/类型 + 基本医学对应关系（如\"这是一阶系统，对应药物代谢\"）。\n"
            "- 0.75 — 基本建模：给出模型名称但医学对应关系模糊，或给出类型但无医学对应。\n"
            "- 0.5 — 部分建模：仅给出模型类别（如\"微分方程\"）但无具体类型或医学对应。\n"
            "- 0.25 — 有限建模：提到\"可以建模\"但未给出任何模型信息。\n"
            "- 0.0 — 无建模：未提供模型，或模型与医学场景完全无关。"
        ),
        "L2": (
            "## 评分标准（L2-标准：完整模型框架）\n"
            "- 1.0 — 完整建模：提供完整模型框架（状态方程/传递函数），参数有物理意义，医学对应清晰。\n"
            "- 0.75 — 基本建模：模型框架正确但参数解释不完整，或医学对应有 1 处遗漏。\n"
            "- 0.5 — 部分建模：有模型框架但参数估计有误，或模型与医学系统对应关系模糊。\n"
            "- 0.25 — 有限建模：仅给出模型名称或形式，无具体参数或医学对应。\n"
            "- 0.0 — 无建模：未提供数学模型，或模型完全错误。"
        ),
        "L3": (
            "## 评分标准（L3-进阶：完整建模 + 参数估计 + 假设讨论）\n"
            "- 1.0 — 完整建模：完整建模过程 + 参数估计 + 医学对应 + 模型假设与适用范围讨论。\n"
            "- 0.75 — 基本建模：建模完整但假设讨论不充分，或参数估计有 1 处错误。\n"
            "- 0.5 — 部分建模：模型框架正确但参数估计不完整，或缺少假设讨论。\n"
            "- 0.25 — 有限建模：仅有模型框架骨架，无参数估计和医学对应。\n"
            "- 0.0 — 无建模：模型框架错误或完全缺失。"
        ),
        "L4": (
            "## 评分标准（L4-高级：多方案建模对比 + 最优选择论证）\n"
            "- 1.0 — 完整建模：提出多种建模方案并对比，论证最优选择的临床约束合理性。\n"
            "- 0.75 — 基本建模：提出多种方案但对比分析不够深入，或最优选择论证有 1 处逻辑缺陷。\n"
            "- 0.5 — 部分建模：仅提出 1 种方案但讨论了替代方案的局限性，缺乏系统对比。\n"
            "- 0.25 — 有限建模：仅给出单一模型，无任何对比或约束讨论。\n"
            "- 0.0 — 无建模：建模完全错误或缺失。"
        ),
    }
    sys_prompt = (
        "你是一位医学与控制科学跨领域评分专家。你需要评估模型为医学系统建立数学模型的能力。\n\n"
        "## 评分维度：model（数学建模）\n\n"
        f"{criteria.get(difficulty, criteria['L2'])}\n\n"
        "## 评判原则\n"
        "- 接受不同但等价的数学表达（如状态空间 vs 传递函数）\n"
        "- 关注参数物理意义与医学参数的对应关系\n"
        "- 若模型推导逻辑正确但符号不同，应视为有效\n\n"
        "请严格按照以下 JSON 格式输出，不要输出任何其他内容：\n"
        '{"score": <分数>, "reason": "<评分理由>", "issues": ["<问题1>", ...]}\n'
        "分数只能是 0.0、0.25、0.5、0.75、1.0 之一。如果没有问题，issues 为空列表 []。"
    )
    usr_template = (
        "## 问题\n{question}\n\n"
        "## 标准答案\n{expected_answer}\n\n"
        "## 模型回答\n{model_answer}\n\n"
        "请根据评分规则对模型回答的数学建模质量进行评分。"
    )
    return sys_prompt, usr_template


def _build_transfer_rubric(difficulty: str) -> tuple[str, str]:
    """Build transfer-dimension rubric for given difficulty."""
    criteria = {
        "L1": (
            "## 评分标准（L1-基础：定性预测 1 个影响）\n"
            "- 1.0 — 完整预测：给出 1 个合理的定性预测（如\"参数增加会导致响应变慢\"），逻辑清晰。\n"
            "- 0.75 — 基本预测：有定性预测但逻辑推导不够清晰，或预测方向正确但理由不充分。\n"
            "- 0.5 — 部分预测：提到\"参数会影响结果\"但无具体预测内容。\n"
            "- 0.25 — 有限预测：仅提到控制方法\"可能有用\"，无任何具体预测。\n"
            "- 0.0 — 无预测：未涉及预测或迁移分析，或分析完全错误。"
        ),
        "L2": (
            "## 评分标准（L2-标准：定性预测 + 逻辑推导）\n"
            "- 1.0 — 完整预测：给出合理定性预测 + 清晰的逻辑推导链（因果关系明确）。\n"
            "- 0.75 — 基本预测：有定性预测和逻辑推导，但推导链有 1 处跳跃。\n"
            "- 0.5 — 部分预测：有定性预测但逻辑支撑不足，或推导链不完整。\n"
            "- 0.25 — 有限预测：仅提到\"可能有影响\"，无具体推导。\n"
            "- 0.0 — 无预测：未涉及预测或分析完全错误。"
        ),
        "L3": (
            "## 评分标准（L3-进阶：量化预测 + 临床意义）\n"
            "- 1.0 — 完整预测：提供量化预测（如\"增益增加20%导致超调增加15%\"）+ 临床意义讨论。\n"
            "- 0.75 — 基本预测：有量化预测但临床意义讨论不充分，或临床讨论深入但量化不足。\n"
            "- 0.5 — 部分预测：有定性预测但无量化分析，或量化分析缺乏逻辑推导。\n"
            "- 0.25 — 有限预测：仅提到\"参数会影响结果\"，无具体预测内容。\n"
            "- 0.0 — 无预测：未涉及预测或迁移分析，或分析完全错误。"
        ),
        "L4": (
            "## 评分标准（L4-高级：量化预测 + 多因素分析 + 实施约束）\n"
            "- 1.0 — 完整预测：量化预测 + 多因素交互分析 + 临床实施约束讨论 + 可行建议。\n"
            "- 0.75 — 基本预测：量化预测 + 多因素分析但实施约束讨论不充分，或缺少可行建议。\n"
            "- 0.5 — 部分预测：有量化预测和单因素分析，但未讨论多因素交互或实施约束。\n"
            "- 0.25 — 有限预测：仅有定性预测，无量化分析或多因素讨论。\n"
            "- 0.0 — 无预测：未涉及预测或分析完全错误。"
        ),
    }
    sys_prompt = (
        "你是一位医学与控制科学跨领域评分专家。你需要评估模型基于控制理论对医学系统进行预测和跨域迁移分析的能力。\n\n"
        "## 评分维度：transfer（预测与迁移）\n\n"
        f"{criteria.get(difficulty, criteria['L2'])}\n\n"
        "## 评判原则\n"
        "- 关注预测的合理性和临床相关性\n"
        "- 量化分析不要求精确数值，但需有逻辑推导过程\n"
        "- 跨域迁移讨论应涉及控制理论到医学的实际应用价值\n\n"
        "请严格按照以下 JSON 格式输出，不要输出任何其他内容：\n"
        '{"score": <分数>, "reason": "<评分理由>", "issues": ["<问题1>", ...]}\n'
        "分数只能是 0.0、0.25、0.5、0.75、1.0 之一。如果没有问题，issues 为空列表 []。"
    )
    usr_template = (
        "## 问题\n{question}\n\n"
        "## 标准答案\n{expected_answer}\n\n"
        "## 模型回答\n{model_answer}\n\n"
        "请根据评分规则对模型回答的预测与迁移分析质量进行评分。"
    )
    return sys_prompt, usr_template


# ---------------------------------------------------------------------------
# Build rubric registry: {(dimension, difficulty): (sys_prompt, usr_template)}
# ---------------------------------------------------------------------------

_RUBRIC_BUILDERS = {
    "identify": _build_identify_rubric,
    "model": _build_model_rubric,
    "transfer": _build_transfer_rubric,
}

MEDICAL_PROMPTS: dict[tuple[str, str], tuple[str, str]] = {}
for _dim, _builder in _RUBRIC_BUILDERS.items():
    for _diff in ("L1", "L2", "L3", "L4"):
        MEDICAL_PROMPTS[(_dim, _diff)] = _builder(_diff)
